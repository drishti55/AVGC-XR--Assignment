"""Ask the assignment's sample questions against the RUNNING API and record the real answers.

Run (backend must be running on :8000):  uv run python scripts/generate_samples.py [--prefer-primary]
Writes docs/SAMPLE_RESPONSES.md. The responses are recorded as returned; nothing is edited by hand.

--prefer-primary: if an answer came from a fallback model (or no model) because Gemini Flash was
overloaded, wait and ask again (up to 3 times). Only the model changes, never the answer; the file records
which model answered and how many attempts it took.
"""
import sys
import time
from datetime import date, datetime
from pathlib import Path

import httpx

API = "http://localhost:8000"
OUT = Path(__file__).resolve().parents[2] / "docs" / "SAMPLE_RESPONSES.md"

QUESTIONS = [
    "What does Garuda Purana explain about karma?",
    "What does the text describe about the soul?",
    "What is the significance of good deeds?",
    "गरुड़ पुराण में कर्म के बारे में क्या बताया गया है?",
    "गरुड़ पुराण के अनुसार मृत्यु के बाद आत्मा की यात्रा का क्या वर्णन है?",
]
EXTRA = ["Who won the 2011 Cricket World Cup?"]   # shows the "not in knowledge base" behaviour


def ask(client: httpx.Client, q: str) -> dict:
    for attempt in range(3):
        r = client.post(f"{API}/ask", json={"question": q}, timeout=180)
        if r.status_code == 429:                       # our own rate limit: wait and retry
            time.sleep(int(r.headers.get("Retry-After", "10")))
            continue
        r.raise_for_status()
        return r.json()
    raise RuntimeError(f"rate limited 3 times: {q}")


def ask_preferring_primary(client: httpx.Client, q: str, prefer: bool) -> tuple[dict, int]:
    b = ask(client, q)
    attempts = 1
    while prefer and (b.get("notice") or "").startswith(("fallback_used", "llm_unavailable")) and attempts < 4:
        print(f"  fallback used ({b['notice']}), retrying in 30 s: {q[:50]}")
        time.sleep(30)
        b = ask(client, q)
        attempts += 1
    return b, attempts


def render(n: int, q: str, b: dict, attempts: int = 1) -> str:
    lines = [f"## {n}. {q}", "",
             f"*Language detected:* `{b['language']}` · *answerable:* `{b['answerable']}` · "
             f"*model:* `{b['model']}` · *time:* {b['latency_ms'] / 1000:.1f} s"
             + (f" · *notice:* `{b['notice']}`" if b["notice"] else "")
             + (f" · *attempts:* {attempts} (primary model was overloaded)" if attempts > 1 else ""), "",
             f"**{b['answer_label']}**", ""]
    lines += ["> " + line if line else ">" for line in b["answer"].splitlines()]
    if b["sources"]:
        lines += ["", "**Cited passages** (text shown in the app verbatim from the knowledge base):", ""]
        for s in b["sources"]:
            lines.append(f"- `{s['id']}`: Chapter {s['chapter']} *{s['chapter_title']}*, verses {s['verse_ref_en']} "
                         f"(Wood 1911 p. {s['page_en']}; Gita Press 1416 p. {s['page_sa']}), relevance {s['relevance']}")
    r = b["retrieval"]
    lines += ["", f"<sub>Retrieval: {r['mode']}, gate {'passed' if r['passed_gate'] else 'refused'} "
                  f"(best cosine {r['best_cosine']}, best BM25 {r['best_bm25']}); retrieved "
                  f"{', '.join(x['id'] for x in r['retrieved']) or '—'}</sub>", ""]
    return "\n".join(lines)


def main() -> int:
    with httpx.Client() as client:
        try:
            health = client.get(f"{API}/health", timeout=5).json()
        except httpx.HTTPError:
            print(f"Backend not reachable at {API}. Start it first: uv run uvicorn app.main:app --port 8000")
            return 1
        prefer = "--prefer-primary" in sys.argv
        results = []
        for i, q in enumerate(QUESTIONS + EXTRA):
            if prefer and i:
                time.sleep(15)       # stay under the free tier's requests-per-minute limit
            results.append((q, *ask_preferring_primary(client, q, prefer)))

    parts = ["# Sample questions and generated responses", "",
             f"Generated on {date.today().isoformat()} by `backend/scripts/generate_samples.py` against the running API "
             f"({health['passages']} passages). Answers are recorded exactly as returned. The text under each "
             "\"AI interpretation\" label is generated by the model; the scripture text itself is shown in the app "
             "from the database.", ""]
    parts += [render(i, q, b, a) for i, (q, b, a) in enumerate(results, start=1)]
    if OUT.exists():                                   # never lose a previous run
        backup = OUT.with_name(f"SAMPLE_RESPONSES.{datetime.now():%Y%m%d-%H%M%S}.bak.md")
        backup.write_text(OUT.read_text(encoding="utf-8"), encoding="utf-8")
        print(f"Previous file kept as {backup.name}")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"Wrote {OUT}")
    for q, b, _ in results:
        print(f"  {b['model'] or '—':32s} answerable={b['answerable']!s:5s} {q[:60]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
